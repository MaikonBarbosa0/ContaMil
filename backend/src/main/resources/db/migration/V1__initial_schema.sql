CREATE TABLE salary_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    effective_month DATE NOT NULL UNIQUE,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount >= 0)
);

CREATE TABLE recurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(180) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    category VARCHAR(80) NOT NULL,
    start_date DATE NOT NULL,
    next_month DATE NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(180) NOT NULL,
    amount NUMERIC(14, 2) NOT NULL CHECK (amount > 0),
    expense_date DATE NOT NULL,
    category VARCHAR(80) NOT NULL,
    recurrence_id BIGINT REFERENCES recurrences(id),
    occurrence_month DATE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT expense_occurrence_unique UNIQUE (recurrence_id, occurrence_month),
    CONSTRAINT expense_occurrence_consistent CHECK (
        (recurrence_id IS NULL AND occurrence_month IS NULL) OR
        (recurrence_id IS NOT NULL AND occurrence_month IS NOT NULL)
    )
);

CREATE INDEX expenses_visible_date_idx ON expenses (deleted, expense_date);
